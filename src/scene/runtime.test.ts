// @vitest-environment node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { build } from "esbuild";
import { describe, expect, it } from "vitest";

/**
 * The standalone scene page carries the scene compositor as one script,
 * bundled from `src/embed/scene-page.ts`. When the compositor (or anything
 * it imports) changes, this test fails until the bundle is written again
 * with `pnpm scene:runtime` (which runs it with UPDATE_SCENE_RUNTIME=1).
 */
const RUNTIME_FILE = resolve("src/scene/runtime.generated.ts");

async function bundle(): Promise<string> {
  const result = await build({
    entryPoints: [resolve("src/embed/scene-page.ts")],
    bundle: true,
    format: "iife",
    minify: true,
    target: "es2022",
    platform: "browser",
    write: false,
    legalComments: "none",
    logLevel: "silent",
  });
  const code = result.outputFiles[0]!.text.trim();
  return [
    "// Generated by `pnpm scene:runtime` from src/embed/scene-page.ts (src/scene/runtime.test.ts): do not edit.",
    "// The standalone scene page's script: the scene compositor and the page's controls, as one string.",
    "",
    `export const SCENE_RUNTIME = ${JSON.stringify(code)};`,
    "",
  ].join("\n");
}

describe("the standalone scene page's script", () => {
  it("is up to date with the compositor (pnpm scene:runtime writes it)", async () => {
    const ts = await bundle();
    if (process.env.UPDATE_SCENE_RUNTIME) writeFileSync(RUNTIME_FILE, ts);
    expect(existsSync(RUNTIME_FILE) && readFileSync(RUNTIME_FILE, "utf8") === ts, "Run `pnpm scene:runtime`: the scene compositor has changed.").toBe(true);
  });

  it("does not carry the catalog", async () => {
    const { SCENE_RUNTIME } = await import("./runtime.generated.js");
    expect(SCENE_RUNTIME.length).toBeLessThan(200_000);
    expect(SCENE_RUNTIME).not.toContain("meta.generated");
    expect(SCENE_RUNTIME).not.toContain("loadEffect");
  });
});
